import os
import cv2
import torch
import numpy as np
from PIL import Image
from torchvision import transforms


class DermAIPreprocessor:
    def __init__(self, target_size=(224, 224), apply_clahe=True):
        self.target_size = target_size
        self.apply_clahe = apply_clahe
        self.clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
        self.torch_transforms = transforms.Compose([
            transforms.ToTensor(),
            transforms.Normalize(
                mean=[0.485, 0.456, 0.406],
                std=[0.229, 0.224, 0.225]
            )
        ])

    def process(self, image_path: str) -> torch.Tensor:
        # 1. Integrity Validation
        if not os.path.exists(image_path):
            raise FileNotFoundError(f"File not found: {image_path}")
        with Image.open(image_path) as img:
            img.verify()

        img_bgr = cv2.imread(image_path)
        if img_bgr is None:
            raise ValueError(f"Corrupted or unreadable image file: {image_path}")

        # 2. CLAHE Contrast Enhancement
        if self.apply_clahe:
            lab = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2LAB)
            l, a, b = cv2.split(lab)
            l_clahe = self.clahe.apply(l)
            lab_clahe = cv2.merge((l_clahe, a, b))
            img_bgr = cv2.cvtColor(lab_clahe, cv2.COLOR_LAB2BGR)

        # 3. RGB Conversion & Resizing
        img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
        img_resized = cv2.resize(img_rgb, self.target_size, interpolation=cv2.INTER_LINEAR)

        # 4. PyTorch Normalization & Batch Dimensions
        tensor = self.torch_transforms(img_resized)
        return tensor.unsqueeze(0)


